/**
 * The {@code HelpInterface} defines a method to provide help information about supported commands.
 */
public interface HelpInterface {

    /**
     * Prints information about supported commands to the console.
     * <p>
     * This method prints a list of supported commands and their descriptions to the standard output,
     * typically for user reference and guidance.
     * </p>
     */
    void execute();
}
